#!/usr/bin/env bash
# Regenerates the settings table in docs/configuration.md from AGBOX_SCHEMA (lib/config.sh),
# so the docs can never drift from the code. CI fails if the committed docs are stale.
#   scripts/gen-config-docs.sh          # rewrite the docs
#   scripts/gen-config-docs.sh --check  # exit 1 if the docs are out of date
set -euo pipefail

ROOT=$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)
DOC="$ROOT/docs/configuration.md"
BEGIN='<!-- settings:begin (generated by scripts/gen-config-docs.sh, do not edit) -->'
END='<!-- settings:end -->'

# shellcheck source=lib/core.sh
source "$ROOT/lib/core.sh"
# shellcheck source=lib/config.sh
source "$ROOT/lib/config.sh"

table() {
  local entry key default desc
  printf '| Setting | Default | Description |\n|---|---|---|\n'
  for entry in "${AGBOX_SCHEMA[@]}"; do
    IFS='|' read -r key default desc <<<"$entry"
    # shellcheck disable=SC2016 # literal backticks for markdown
    printf '| `AGBOX_%s` | %s | %s |\n' "$key" "${default:+\`$default\`}" "$desc"
  done
}

current=$(<"$DOC")
[[ $current == *"$BEGIN"* && $current == *"$END"* ]] || { echo "markers missing in $DOC" >&2; exit 1; }
updated="${current%%"$BEGIN"*}$BEGIN"$'\n'"$(table)"$'\n'"$END${current#*"$END"}"

if [[ ${1:-} == --check ]]; then
  if [[ $updated != "$current" ]]; then
    echo "docs/configuration.md is out of date: run scripts/gen-config-docs.sh" >&2
    exit 1
  fi
  echo "docs/configuration.md is up to date"
else
  printf '%s\n' "$updated" >"$DOC"
  echo "updated $DOC"
fi
